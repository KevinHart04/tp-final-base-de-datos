-- TPFI Base de Datos - Sistema de Justicia
-- 01_creacion.sql
-- Correr conectado a la base justicia.

BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'propietario_sistema') THEN
        CREATE ROLE propietario_sistema NOLOGIN;
    END IF;
END $$;

DROP TABLE IF EXISTS CambioCondena CASCADE;
DROP TABLE IF EXISTS Condena CASCADE;
DROP TABLE IF EXISTS Acusado CASCADE;
DROP TABLE IF EXISTS CausaJudicial CASCADE;
DROP TABLE IF EXISTS PropiedadDomicilio CASCADE;
DROP TABLE IF EXISTS RelacionFamiliar CASCADE;
DROP TABLE IF EXISTS Persona CASCADE;
DROP TABLE IF EXISTS UnidadCarcelaria CASCADE;
DROP TABLE IF EXISTS Domicilio CASCADE;
DROP TABLE IF EXISTS Fiscalia CASCADE;
DROP TABLE IF EXISTS Secretaria CASCADE;
DROP TABLE IF EXISTS Profesion CASCADE;
DROP TABLE IF EXISTS Nacionalidad CASCADE;

DROP DOMAIN IF EXISTS dni, nombre, direccion, razon, duracion_meses,
    estado_acusado, nivel_educacion, estado_civil,
    tipo_parentesco, tipo_cambio_condena CASCADE;

-- Dominios
CREATE DOMAIN dni AS INTEGER CHECK (VALUE > 0);
CREATE DOMAIN nombre AS VARCHAR(100) CHECK (TRIM(VALUE) <> '');
CREATE DOMAIN direccion AS VARCHAR(200) CHECK (TRIM(VALUE) <> '');
CREATE DOMAIN razon AS VARCHAR(255) CHECK (TRIM(VALUE) <> '');
CREATE DOMAIN duracion_meses AS INTEGER CHECK (VALUE > 0);

CREATE DOMAIN estado_acusado AS VARCHAR(20)
    CHECK (VALUE IN ('INDAGADO', 'PROCESADO', 'CONDENADO', 'SOBRESEIDO'));
CREATE DOMAIN nivel_educacion AS VARCHAR(20)
    CHECK (VALUE IN ('SIN_INSTRUCCION', 'PRIMARIO', 'SECUNDARIO', 'TERCIARIO', 'UNIVERSITARIO'));
CREATE DOMAIN estado_civil AS VARCHAR(20)
    CHECK (VALUE IN ('SOLTERO', 'CASADO', 'DIVORCIADO', 'VIUDO', 'CONVIVIENTE'));
CREATE DOMAIN tipo_parentesco AS VARCHAR(20)
    CHECK (VALUE IN ('MADRE', 'PADRE', 'HERMANO', 'HIJO'));
CREATE DOMAIN tipo_cambio_condena AS VARCHAR(30)
    CHECK (VALUE IN ('EXTENSION_CONDENA', 'REDUCCION_CONDENA',
                     'CAMBIO_UNIDAD_CARCELARIA', 'PRISION_DOMICILIARIA'));

-- Tablas
CREATE TABLE Nacionalidad (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre nombre NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE Profesion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre nombre NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE Secretaria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre nombre NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE Fiscalia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre nombre NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE Domicilio (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    direccion direccion NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE UnidadCarcelaria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre nombre NOT NULL,
    domicilio_id INTEGER NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (domicilio_id),
    FOREIGN KEY (domicilio_id) REFERENCES Domicilio(id) ON DELETE RESTRICT
);

CREATE TABLE Persona (
    dni dni NOT NULL,
    nombres nombre NOT NULL,
    apellidos nombre NOT NULL,
    fechaNacimiento DATE NOT NULL,
    estadoCivil estado_civil NOT NULL,
    nivelEducacion nivel_educacion NOT NULL,
    nacionalidad_id INTEGER NOT NULL,
    profesion_id INTEGER NULL,
    PRIMARY KEY (dni),
    FOREIGN KEY (nacionalidad_id) REFERENCES Nacionalidad(id) ON DELETE RESTRICT,
    FOREIGN KEY (profesion_id) REFERENCES Profesion(id) ON DELETE RESTRICT
);

CREATE TABLE RelacionFamiliar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo tipo_parentesco NOT NULL,
    persona_dni dni NOT NULL,
    familiar_dni dni NOT NULL,
    PRIMARY KEY (id),
    CHECK (familiar_dni <> persona_dni),
    FOREIGN KEY (persona_dni) REFERENCES Persona(dni) ON DELETE RESTRICT,
    FOREIGN KEY (familiar_dni) REFERENCES Persona(dni) ON DELETE RESTRICT
);

CREATE TABLE PropiedadDomicilio (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    persona_dni dni NOT NULL,
    domicilio_id INTEGER NOT NULL,
    fechaDesde DATE NOT NULL,
    fechaHasta DATE NULL,
    esPrincipal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id),
    CHECK (fechaHasta IS NULL OR fechaHasta >= fechaDesde),
    FOREIGN KEY (persona_dni) REFERENCES Persona(dni) ON DELETE RESTRICT,
    FOREIGN KEY (domicilio_id) REFERENCES Domicilio(id) ON DELETE RESTRICT
);

CREATE TABLE CausaJudicial (
    numeroInternoRegistro INTEGER NOT NULL,
    fechaAlta DATE NOT NULL,
    fechaResolucion DATE NULL,
    secretaria_id INTEGER NOT NULL,
    fiscalia_id INTEGER NOT NULL,
    juez_dni dni NOT NULL,
    secretario_dni dni NOT NULL,
    PRIMARY KEY (numeroInternoRegistro),
    CHECK (fechaResolucion IS NULL OR fechaResolucion >= fechaAlta),
    FOREIGN KEY (secretaria_id) REFERENCES Secretaria(id) ON DELETE RESTRICT,
    FOREIGN KEY (fiscalia_id) REFERENCES Fiscalia(id) ON DELETE RESTRICT,
    FOREIGN KEY (juez_dni) REFERENCES Persona(dni) ON DELETE RESTRICT,
    FOREIGN KEY (secretario_dni) REFERENCES Persona(dni) ON DELETE RESTRICT
);

CREATE TABLE Acusado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estadoActual estado_acusado NOT NULL DEFAULT 'INDAGADO',
    persona_dni dni NOT NULL,
    causa_id INTEGER NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (persona_dni, causa_id),
    FOREIGN KEY (persona_dni) REFERENCES Persona(dni) ON DELETE RESTRICT,
    FOREIGN KEY (causa_id) REFERENCES CausaJudicial(numeroInternoRegistro) ON DELETE RESTRICT
);

CREATE TABLE Condena (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fechaInicio DATE NOT NULL,
    duracionMeses duracion_meses NOT NULL,
    fechaBajaLibertad DATE NULL,
    acusado_id INTEGER NOT NULL,
    domicilio_id INTEGER NULL,
    unidadCarcelaria_id INTEGER NULL,
    PRIMARY KEY (id),
    UNIQUE (acusado_id),
    -- exactamente uno de los dos lugares de cumplimiento
    CHECK ((domicilio_id IS NULL) <> (unidadCarcelaria_id IS NULL)),
    CHECK (fechaBajaLibertad IS NULL
           OR fechaBajaLibertad > fechaInicio + duracionMeses * INTERVAL '1 month'),
    FOREIGN KEY (acusado_id) REFERENCES Acusado(id) ON DELETE RESTRICT,
    FOREIGN KEY (domicilio_id) REFERENCES Domicilio(id) ON DELETE RESTRICT,
    FOREIGN KEY (unidadCarcelaria_id) REFERENCES UnidadCarcelaria(id) ON DELETE RESTRICT
);

CREATE TABLE CambioCondena (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fechaCambio DATE NOT NULL DEFAULT CURRENT_DATE,
    tipoCambio tipo_cambio_condena NOT NULL,
    razon razon NOT NULL,
    condena_id INTEGER NOT NULL,
    mesesVariacion INTEGER NULL,
    unidadCarcelaria_id INTEGER NULL,
    PRIMARY KEY (id),
    -- meses solo en extensiones y reducciones
    CHECK (
        (tipoCambio IN ('EXTENSION_CONDENA', 'REDUCCION_CONDENA')
            AND mesesVariacion IS NOT NULL AND mesesVariacion > 0)
        OR (tipoCambio IN ('CAMBIO_UNIDAD_CARCELARIA', 'PRISION_DOMICILIARIA')
            AND mesesVariacion IS NULL)
    ),
    -- unidad de destino solo en cambios de unidad
    CHECK (
        (tipoCambio = 'CAMBIO_UNIDAD_CARCELARIA' AND unidadCarcelaria_id IS NOT NULL)
        OR (tipoCambio <> 'CAMBIO_UNIDAD_CARCELARIA' AND unidadCarcelaria_id IS NULL)
    ),
    FOREIGN KEY (condena_id) REFERENCES Condena(id) ON DELETE RESTRICT,
    FOREIGN KEY (unidadCarcelaria_id) REFERENCES UnidadCarcelaria(id) ON DELETE RESTRICT
);

ALTER TABLE Nacionalidad OWNER TO propietario_sistema;
ALTER TABLE Profesion OWNER TO propietario_sistema;
ALTER TABLE Secretaria OWNER TO propietario_sistema;
ALTER TABLE Fiscalia OWNER TO propietario_sistema;
ALTER TABLE Domicilio OWNER TO propietario_sistema;
ALTER TABLE UnidadCarcelaria OWNER TO propietario_sistema;
ALTER TABLE Persona OWNER TO propietario_sistema;
ALTER TABLE RelacionFamiliar OWNER TO propietario_sistema;
ALTER TABLE PropiedadDomicilio OWNER TO propietario_sistema;
ALTER TABLE CausaJudicial OWNER TO propietario_sistema;
ALTER TABLE Acusado OWNER TO propietario_sistema;
ALTER TABLE Condena OWNER TO propietario_sistema;
ALTER TABLE CambioCondena OWNER TO propietario_sistema;

COMMIT;
